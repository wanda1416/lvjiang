def _append(path: Path, pairs: dict[str, str], header: str) -> None:
    """把新条目追加到词表末尾（YAML 字典顺序无意义，追加最安全）。"""
    body = path.read_text(encoding="utf-8")
    if not body.endswith("\n"):
        body += "\n"
    block = yaml.safe_dump(pairs, allow_unicode=True, sort_keys=True,
                           default_flow_style=False, width=100000)
    path.write_text(body + header + block, encoding="utf-8", newline="\n")


def main() -> int:
    written = 0
    for lang in LANGS:
        pairs = {zh: tr[lang] for zh, tr in T.items()}
        assert len(pairs) == len(T), lang
        target = I18N / lang / "notices.yaml"
        _append(target, pairs, "\n# ── 反馈与建议（0.15.18 改版）──\n")
        written += len(pairs)
    print(f"写入 {len(T)} 条 × {len(LANGS)} 种语言 = {written} 条")
    return 0


